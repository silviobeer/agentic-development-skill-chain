#!/usr/bin/env node
//
// gen-component-registry.mjs — generate docs/components.md from the code.
//
// The registry is NOT hand-maintained. Every component carries its own
// metadata in a doc block above the export; this script collects them.
// One source of truth (the component file), no second list to drift.
//
//   /** Actions. Not for navigation — use Link.
//    *  @variants primary|secondary|ghost|destructive  @sizes sm|md|lg
//    *  @states hover|focus|disabled|loading */
//   export function Button(props) { … }
//
// Usage:
//   node scripts/gen-component-registry.mjs            write docs/components.md
//   node scripts/gen-component-registry.mjs --check    verify it is current (CI/wave gate)
//   node scripts/gen-component-registry.mjs --force    overwrite a hand-written registry (one-time migration)
//   node scripts/gen-component-registry.mjs --selftest  run the built-in check
//
// Exit: 0 ok · 1 drift, undocumented component, or missing showcase section
//       2 usage/IO error
//       3 hand-written registry, refused (migration pending — not a failure)
//
// ponytail: regex scan over `export function|const <Uppercase>` in .tsx/.jsx,
// not a real AST parse, and React-shaped. Good enough while the chain targets
// React; swap in a parser (or per-stack extractors for Vue SFC / Svelte) when
// a project needs it.

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync, mkdirSync, rmSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { tmpdir } from "node:os";
import assert from "node:assert/strict";

const OUT = "docs/components.md";
const MARKER = "GENERATED by scripts/gen-component-registry.mjs";

// A registry this script did not write is hand-maintained: overwriting it
// would silently drop purpose texts nobody can recover from the code. Refuse
// and let a human migrate — that is a one-time decision, not a gate.
function handWritten(target) {
  return existsSync(target) && !readFileSync(target, "utf8").includes(MARKER);
}

const HEADER = () => [
  "# Component Registry",
  "",
  `<!-- ${MARKER} — do not edit by hand.`,
  "     Component metadata lives in the doc block above each export. -->",
  "",
];

const SRC_EXT = /\.(tsx|jsx)$/;
const SKIP = /\.(test|spec|stories)\.|__tests__|node_modules/;

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (SRC_EXT.test(p) && !SKIP.test(p)) out.push(p);
  }
  return out;
}

// src/components/ui/button.tsx -> src/components, src/features/x/components
function componentDirs(root) {
  const dirs = [join(root, "src", "components")];
  const features = join(root, "src", "features");
  if (existsSync(features)) {
    for (const f of readdirSync(features)) {
      const d = join(features, f, "components");
      if (existsSync(d)) dirs.push(d);
    }
  }
  return dirs.filter(existsSync);
}

function importPath(root, file) {
  let p = relative(root, file).split(sep).join("/");
  p = p.replace(/^src\//, "@/").replace(SRC_EXT, "").replace(/\/index$/, "");
  return p;
}

// The showcase renders every registered component under an anchor. Only the
// page can prove a component really looks right, so a registered component
// with no section on it is drift like a stale table is drift.
const SHOWCASE_ROUTES = [
  "src/app/dev/components/page.tsx",
  "src/app/dev/components/page.jsx",
  "src/pages/dev/components.tsx",
  "src/routes/dev/components/+page.svelte",
];

// BulkBar -> bulk-bar, UIButton -> ui-button
const kebab = (name) =>
  name
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();

function findFile(dir, name, depth = 6) {
  if (depth < 0 || !existsSync(dir)) return null;
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) {
      const hit = findFile(p, name, depth - 1);
      if (hit) return hit;
    } else if (entry === name) return p;
  }
  return null;
}

function findShowcase(root) {
  for (const p of SHOWCASE_ROUTES) if (existsSync(join(root, p))) return join(root, p);
  // pre-scaffold fallback written by 1c_frontend-design
  return findFile(join(root, "specs"), "component-showcase.html");
}

// The doc block directly above an export, if any.
function parseDoc(block) {
  if (!block) return null;
  const body = block
    .replace(/^\s*\/\*\*/, "")
    .replace(/\*\/\s*$/, "")
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, "").trim())
    .join(" ")
    .trim();
  const tag = (name) => {
    const m = body.match(new RegExp(`@${name}\\s+(\\S+)`));
    return m ? m[1] : "—";
  };
  const purpose = body.split(/@\w+/)[0].trim().replace(/\s+/g, " ");
  return { purpose, variants: tag("variants"), sizes: tag("sizes"), states: tag("states") };
}

function collect(root) {
  const found = [];
  for (const dir of componentDirs(root)) {
    for (const file of walk(dir)) {
      const src = readFileSync(file, "utf8");
      // doc block (optional) immediately followed by an exported Capitalised binding
      const re = /(\/\*\*[\s\S]*?\*\/\s*)?export\s+(?:default\s+)?(?:function|const)\s+([A-Z]\w*)/g;
      let m;
      while ((m = re.exec(src)) !== null) {
        found.push({ name: m[2], import: importPath(root, file), file, ...(parseDoc(m[1]) ?? { purpose: "", variants: "—", sizes: "—", states: "—" }) });
      }
    }
  }
  found.sort((a, b) => a.name.localeCompare(b.name));
  return found;
}

function render(entries) {
  const lines = [...HEADER()];
  if (entries.length === 0) {
    lines.push("_No components yet._", "");
    return lines.join("\n");
  }
  lines.push(
    "| Component | Import | Purpose | Variants | Sizes | States |",
    "|---|---|---|---|---|---|",
    ...entries.map((e) => `| ${e.name} | \`${e.import}\` | ${e.purpose || "—"} | ${e.variants} | ${e.sizes} | ${e.states} |`),
    "",
  );
  return lines.join("\n");
}

function run(root, check, force) {
  const entries = collect(root);
  const undocumented = entries.filter((e) => !e.purpose);
  const next = render(entries);
  const target = join(root, OUT);

  if (handWritten(target) && !force) {
    console.error(`❌ ${OUT} is hand-written — this script did not generate it. Migrate once:`);
    console.error(`   1) move each entry's purpose + variants/sizes/states into a doc block above the component export`);
    console.error(`   2) re-run with --force · 3) review the diff before committing`);
    return 3; // migration pending, not a defect — callers may log and continue
  }

  if (!check) {
    mkdirSync(join(root, "docs"), { recursive: true });
    writeFileSync(target, next);
    console.log(`✓ ${OUT} — ${entries.length} component(s)`);
  }

  let bad = 0;
  for (const e of undocumented) {
    console.error(`❌ ${e.name} (${relative(root, e.file)}) has no doc block — add a purpose line above the export`);
    bad = 1;
  }
  // No showcase yet (backend repo, pre-scaffold greenfield) → nothing to verify.
  const showcase = findShowcase(root);
  if (showcase) {
    const page = readFileSync(showcase, "utf8");
    for (const e of entries) {
      if (page.includes(`id="${kebab(e.name)}"`)) continue;
      console.error(`❌ ${e.name} has no showcase section in ${relative(root, showcase)} — add id="${kebab(e.name)}"`);
      bad = 1;
    }
  }

  if (check) {
    const current = existsSync(target) ? readFileSync(target, "utf8") : "";
    if (current !== next) {
      console.error(`❌ ${OUT} is stale — run: node scripts/gen-component-registry.mjs`);
      bad = 1;
    }
    if (!bad) console.log(`✓ ${OUT} current — ${entries.length} component(s)`);
  }
  return bad;
}

function selftest() {
  const root = join(tmpdir(), `gen-registry-selftest-${process.pid}`);
  rmSync(root, { recursive: true, force: true });
  mkdirSync(join(root, "src", "components", "ui"), { recursive: true });
  mkdirSync(join(root, "src", "features", "orders", "components"), { recursive: true });

  writeFileSync(
    join(root, "src", "components", "ui", "button.tsx"),
    `/** Actions. Not for navigation — use Link.\n *  @variants primary|ghost  @sizes sm|md\n *  @states hover|disabled */\nexport function Button() {}\n`,
  );
  writeFileSync(join(root, "src", "components", "ui", "button.test.tsx"), `export function Ignored() {}\n`);
  writeFileSync(join(root, "src", "features", "orders", "components", "bulk-bar.tsx"), `export const BulkBar = () => null\n`);

  assert.equal(run(root, false, false), 1, "undocumented component must be reported");
  const md = readFileSync(join(root, "docs", "components.md"), "utf8");
  assert.match(md, /\| Button \| `@\/components\/ui\/button` \| Actions\. Not for navigation — use Link\. \| primary\|ghost \| sm\|md \| hover\|disabled \|/);
  assert.match(md, /\| BulkBar \| `@\/features\/orders\/components\/bulk-bar` \| — \| — \| — \| — \|/);
  assert.doesNotMatch(md, /Ignored/, "test files must be skipped");
  assert.equal(run(root, true, false), 1, "check must still flag the undocumented component");

  writeFileSync(join(root, "src", "components", "ui", "card.tsx"), `/** Surface for grouped content. */\nexport function Card() {}\n`);
  assert.equal(readFileSync(join(root, "docs", "components.md"), "utf8"), md, "file unchanged until regenerated");
  assert.equal(run(root, true, false), 1, "new component must make --check fail as stale");

  // a registry this script did not write is never clobbered
  writeFileSync(join(root, "docs", "components.md"), "| Button | hand-maintained |\n");
  assert.equal(run(root, false, false), 3, "hand-written registry must be refused with its own code");
  assert.match(readFileSync(join(root, "docs", "components.md"), "utf8"), /hand-maintained/, "hand-written registry must survive");
  assert.equal(run(root, false, true), 1, "--force overwrites (still 1: BulkBar undocumented)");
  assert.match(readFileSync(join(root, "docs", "components.md"), "utf8"), /GENERATED by/, "--force must regenerate");

  // showcase anchors: only checked once a showcase exists
  writeFileSync(
    join(root, "src", "features", "orders", "components", "bulk-bar.tsx"),
    `/** Bulk actions on a selection. */\nexport const BulkBar = () => null\n`,
  );
  assert.equal(run(root, false, false), 0, "all documented, no showcase → clean");
  const page = join(root, "src", "app", "dev", "components", "page.tsx");
  mkdirSync(join(root, "src", "app", "dev", "components"), { recursive: true });
  writeFileSync(page, `export default function Page() {\n  return <section id="button" />\n}\n`);
  assert.equal(run(root, true, false), 1, "component without a showcase section must fail");
  writeFileSync(page, `export default function Page() {\n  return <><section id="button" /><section id="bulk-bar" /><section id="card" /></>\n}\n`);
  assert.equal(run(root, true, false), 0, "every component anchored → clean");

  rmSync(root, { recursive: true, force: true });
  console.log("✓ selftest passed");
  return 0;
}

const args = process.argv.slice(2);
if (args.includes("--selftest")) process.exit(selftest());
const rootArg = args.find((a) => !a.startsWith("--")) ?? ".";
if (!existsSync(rootArg)) {
  console.error(`root not found: ${rootArg}`);
  process.exit(2);
}
process.exit(run(rootArg, args.includes("--check"), args.includes("--force")));
